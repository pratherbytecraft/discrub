import { describe, it, expect, afterEach } from 'vitest';
import i18next from 'i18next';
import '@/i18n';
import { exportSlug } from '@/utils/exportFileName';
import { EXPORT_FONT_STACK, exportLangTag, scriptJson, viewerStrings } from './exportStrings';
import { generateEmbeddedJs } from './exportHtmlJs';
import { generateExportReadme, generatePlainTextReadme, getExportService } from './exportService';

const BOM = String.fromCharCode(0xfeff);
// Built from code points so the test file itself stays ASCII.
const CHINESE_NAME = String.fromCharCode(0x95f2, 0x804a);

afterEach(async () => {
  await i18next.changeLanguage('en');
});

describe('exportSlug (2.2.9)', () => {
  it('keeps the old result for names with Latin letters or digits', () => {
    expect(exportSlug('General Chat!')).toBe('general_chat');
    expect(exportSlug('__Off-Topic__ 2')).toBe('off_topic_2');
    expect(exportSlug(`${CHINESE_NAME}-general`)).toBe('general');
    expect(exportSlug('')).toBe('');
  });

  it('gives a name with no Latin letters a short code instead of nothing, the same one every time', () => {
    const code = exportSlug(CHINESE_NAME);
    expect(code).toMatch(/^x[0-9a-f]{8}$/);
    expect(exportSlug(CHINESE_NAME)).toBe(code);
    expect(exportSlug(CHINESE_NAME + CHINESE_NAME)).not.toBe(code);
  });

  it('is what the export service uses for file names', () => {
    const service = getExportService();
    expect(service.sanitizeFilename(CHINESE_NAME)).toBe(exportSlug(CHINESE_NAME));
    expect(service.sanitizeFilename(CHINESE_NAME, '42')).toBe(`${exportSlug(CHINESE_NAME)}_42`);
    expect(service.sanitizeFilename('General')).toBe('general');
  });
});

describe('export strings follow the app language (2.2.9)', () => {
  it('tags pages with the language and falls back to en', () => {
    expect(exportLangTag('en')).toBe('en');
    expect(exportLangTag('de')).toBe('de');
    expect(exportLangTag('zh' as never)).toBe('zh-CN');
    expect(exportLangTag('xx' as never)).toBe('en');
  });

  it('carries Chinese capable families in the page font stack', () => {
    expect(EXPORT_FONT_STACK).toContain("'PingFang SC'");
    expect(EXPORT_FONT_STACK).toContain("'Microsoft YaHei'");
    expect(EXPORT_FONT_STACK.trim().endsWith('sans-serif')).toBe(true);
  });

  it('keeps a script block intact whatever the strings hold', () => {
    expect(scriptJson({ a: '</script><b>' })).not.toContain('</script>');
    expect(JSON.parse(scriptJson({ a: '</script><b>' }))).toEqual({ a: '</script><b>' });
  });

  it('writes the viewer wording into the page script in English and in German', async () => {
    expect(viewerStrings().serverNickname).toBe('Server Nickname');
    expect(generateEmbeddedJs()).toContain('"copyId":"Copy ID"');
    await i18next.changeLanguage('de');
    expect(viewerStrings().serverNickname).toBe('Server-Spitzname');
    const js = generateEmbeddedJs();
    expect(js).toContain('"copyId":"ID kopieren"');
    expect(js).toContain('{count} Nachrichten in diesem Export');
    expect(js).not.toContain('Copy ID');
    // The script still parses with the German table in it.
    expect(() => new Function(js)).not.toThrow();
  });

  it('writes the HTML guide in the app language with the language tag and font stack', async () => {
    const en = generateExportReadme({ format: 'html', isDiscordShell: false, isBulk: false, channelName: 'general' });
    expect(en).toContain('<html lang="en">');
    expect(en).toContain('<h2>Getting Started</h2>');
    expect(en).toContain('<strong>Open the HTML file</strong>: Open <code>general</code> in your browser.');
    expect(en).toContain('Format: HTML · Generated by <a href="https://github.com/prathercc/discrub">Discrub</a>');
    await i18next.changeLanguage('de');
    const de = generateExportReadme({ format: 'html', isDiscordShell: true, isBulk: true });
    expect(de).toContain('<html lang="de">');
    expect(de).toContain('<h2>Erste Schritte</h2>');
    expect(de).toContain('Format: HTML (Discord-Layout) · Erstellt mit');
    expect(de).toContain("'PingFang SC'");
    expect(de).not.toContain('Getting Started');
  });

  it('writes the plain text guide in the app language', async () => {
    await i18next.changeLanguage('de');
    const txt = generatePlainTextReadme({ isBulk: false, channelName: 'general' });
    expect(txt).toContain('Discrub-Export\n==============');
    expect(txt).toContain('Öffne general-page-1.txt in einem Texteditor.');
    expect(txt).not.toContain('<');
  });

  it('starts a CSV page with the UTF-8 mark and keeps the column names in English', async () => {
    await i18next.changeLanguage('de');
    const csv = getExportService().generateCSV([], {}, null);
    expect(csv.startsWith(`${BOM}ID,Timestamp,Username,Display Name,Server Nickname`)).toBe(true);
  });
});
